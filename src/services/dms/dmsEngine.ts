/**
 * DMS (Driver Monitoring System) Central Engine
 * 
 * Orchestrates geometry math, PERCLOS window tracking, head pose distraction,
 * phone usage, and seatbelt checks without any DOM dependencies.
 * Generates typed Raasta Kashmir SafetyEvents.
 */

import { Point2D, Point3D, calculateEAR, calculateMAR, estimateHeadPose } from './geometry';
import { PerclosTracker, DrowsinessState } from './perclosTracker';
import { DistractionTracker, GazeDistractionState, YawnState, PhoneUsageState } from './distractionTracker';
import { DMSScheduler } from './dmsScheduler';
import { SafetyEvent, SafetyEventType, SafetyEventSeverity } from '../../types/fleet';
import { dmsTelemetryBus } from './dmsTelemetryBus';

export interface DriverFaceInput {
  leftEyeLandmarks: Point2D[];
  rightEyeLandmarks: Point2D[];
  mouthLandmarks: {
    topLip: Point2D;
    bottomLip: Point2D;
    leftCorner: Point2D;
    rightCorner: Point2D;
  };
  headPoseLandmarks: {
    noseTip: Point3D;
    chin: Point3D;
    leftEye: Point3D;
    rightEye: Point3D;
  };
  timestampMs?: number;
}

export interface DriverCabinInput {
  phone?: {
    isDetected: boolean;
    nearEar: boolean;
    nearLap: boolean;
    confidence: number;
  };
  hands?: {
    leftHandOnWheel: boolean;
    rightHandOnWheel: boolean;
  };
  seatbelt?: {
    isFastened: boolean;
    confidence: number;
  };
  timestampMs?: number;
}

export interface ActiveDMSAlert {
  id: string;
  type: SafetyEventType;
  severity: SafetyEventSeverity;
  title: string;
  message: string;
  timestamp: string;
}

export interface DMSStatus {
  isDriverPresent: boolean;
  handsCount: number;
  phoneInHand: boolean;
  phoneDescription: string;
  drowsiness: DrowsinessState;
  distraction: GazeDistractionState;
  yawn: YawnState;
  phone: PhoneUsageState;
  handsOnWheel: boolean;
  seatbeltFastened: boolean;
  activeAlert: ActiveDMSAlert | null;
  headPose?: {
    yaw: number;
    pitch: number;
    roll: number;
    direction: string;
    isLookingAway?: boolean;
  };
  attentionSummary?: string;
}

export type SafetyEventListener = (event: SafetyEvent) => void;

export class DMSEngine {
  private perclosTracker: PerclosTracker;
  private distractionTracker: DistractionTracker;
  public scheduler: DMSScheduler;

  private listeners: SafetyEventListener[] = [];
  private activeAlert: ActiveDMSAlert | null = null;
  private lastAlertTimestamp: Record<string, number> = {};
  private readonly ALERT_COOLDOWN_MS = 6000; // prevent alert spam

  // Context properties for SafetyEvent creation
  public tripId: string = 'trip_live';
  public busId: string = 'JK01-1234';
  public driverId: string = 'driver_001';
  public schoolId: string = 'school_001';
  public currentSpeed: number = 40;
  public currentLat: number = 34.0837;
  public currentLng: number = 74.7973;

  private handsOnWheel: boolean = true;
  private handsCount: number = 2;
  private seatbeltFastened: boolean = false;
  private isSeatbeltManuallySet: boolean = false;
  private isDriverPresent: boolean = false;
  private phoneInHand: boolean = false;
  private phoneDescription: string = 'Clear';
  private handsOffStartTime: number | null = null;
  private seatbeltOffStartTime: number | null = null;
  private driverAbsentStartTime: number | null = null;
  private phoneInHandStartTime: number | null = null;
  private distractionStartTime: number | null = null;
  private microsleepStartTime: number | null = null;
  private snapshotProvider: (() => string | null) | null = null;

  // Live on-device vision telemetry cache
  private latestVisionPerclos: number = 0.05;
  private latestVisionMicrosleep: boolean = false;
  private latestVisionDistracted: boolean = false;
  private latestVisionDistractionReason: GazeDistractionState['reason'] = 'normal';
  private latestVisionYawn: boolean = false;
  private latestVisionPhone: boolean = false;
  private latestVisionPhoneMode: 'none' | 'calling' | 'texting' = 'none';
  private latestHeadPose: { yaw: number; pitch: number; roll: number; direction: string; isLookingAway?: boolean } = {
    yaw: 0,
    pitch: 0,
    roll: 0,
    direction: 'SEARCHING...',
    isLookingAway: false,
  };
  private latestAttentionSummary: string = 'INITIALIZING REAL-TIME DMS...';

  constructor() {
    this.perclosTracker = new PerclosTracker();
    this.distractionTracker = new DistractionTracker();
    this.scheduler = new DMSScheduler();
  }

  /**
   * Subscribe to safety events generated by the DMS engine.
   */
  public onSafetyEvent(listener: SafetyEventListener): () => void {
    this.listeners.push(listener);
    return () => {
      this.listeners = this.listeners.filter(l => l !== listener);
    };
  }

  /**
   * Process a single frame from the Driver Camera (evaluated at 8-10 FPS).
   */
  public processDriverFaceFrame(input: DriverFaceInput): DMSStatus {
    const now = input.timestampMs || Date.now();
    this.scheduler.markProcessingStart('driver_camera', now);

    try {
      // 1. Calculate EAR for both eyes & average
      const leftEar = calculateEAR(input.leftEyeLandmarks);
      const rightEar = calculateEAR(input.rightEyeLandmarks);
      const avgEar = (leftEar + rightEar) / 2.0;

      // 2. Update PERCLOS & Microsleep State
      const drowsinessState = this.perclosTracker.update(avgEar, now);

      // 3. Head Pose & Gaze Distraction
      const headPose = estimateHeadPose(
        input.headPoseLandmarks.noseTip,
        input.headPoseLandmarks.chin,
        input.headPoseLandmarks.leftEye,
        input.headPoseLandmarks.rightEye
      );
      const distractionState = this.distractionTracker.updateHeadPose(headPose, now);

      // 4. Mouth & Yawn Tracking
      const mar = calculateMAR(
        input.mouthLandmarks.topLip,
        input.mouthLandmarks.bottomLip,
        input.mouthLandmarks.leftCorner,
        input.mouthLandmarks.rightCorner
      );
      const yawnState = this.distractionTracker.updateMouth(mar, now);

      // 5. Evaluate Alert Conditions & Emit Safety Events
      this.evaluateDriverAlerts(drowsinessState, distractionState, yawnState, now);

      return this.getStatus(drowsinessState, distractionState, yawnState);
    } finally {
      this.scheduler.markProcessingEnd('driver_camera');
    }
  }

  /**
   * Process a single frame from the Cabin/Seatbelt Camera (evaluated at 2-3 FPS).
   */
  public processCabinFrame(input: DriverCabinInput): void {
    const now = input.timestampMs || Date.now();
    this.scheduler.markProcessingStart('cabin_camera', now);

    try {
      // 1. Phone Usage
      if (input.phone) {
        const phoneState = this.distractionTracker.evaluatePhoneUsage(input.phone);
        if (phoneState.isUsingPhone && this.canTriggerAlert('phone_use', now)) {
          this.emitEvent({
            type: 'phone_use',
            severity: 'critical',
            confidence: phoneState.confidence,
            source: 'driver_cam',
            title: 'Mobile Phone In Use',
            message: `Driver detected ${phoneState.mode === 'calling' ? 'making a call' : 'texting'} while vehicle is in motion.`,
            durationMs: 1500,
          });
        }
      }

      // 2. Hands on wheel
      if (input.hands) {
        const bothHandsOff = !input.hands.leftHandOnWheel && !input.hands.rightHandOnWheel;
        this.handsOnWheel = !bothHandsOff;

        if (bothHandsOff) {
          if (this.handsOffStartTime === null) this.handsOffStartTime = now;
          const handsOffDuration = now - this.handsOffStartTime;

          if (handsOffDuration >= 2500 && this.canTriggerAlert('hands_off', now)) {
            this.emitEvent({
              type: 'hands_off',
              severity: 'critical',
              confidence: 0.90,
              source: 'driver_cam',
              title: 'Hands Off Steering Wheel',
              message: 'Both hands off steering wheel for >2.5s.',
              durationMs: handsOffDuration,
            });
          }
        } else {
          this.handsOffStartTime = null;
        }
      }

      // 3. Seatbelt compliance (anomaly alert suppressed for now as driver has no seatbelt)
      if (input.seatbelt) {
        this.seatbeltFastened = input.seatbelt.isFastened;
      }
    } finally {
      this.scheduler.markProcessingEnd('cabin_camera');
    }
  }

  private evaluateDriverAlerts(
    drowsiness: DrowsinessState,
    distraction: GazeDistractionState,
    yawn: YawnState,
    now: number
  ): void {
    // Critical: Microsleep (eyes closed > 1.5s)
    if (drowsiness.isMicrosleeping && this.canTriggerAlert('drowsiness_crit', now)) {
      this.emitEvent({
        type: 'drowsiness',
        severity: 'critical',
        confidence: 0.96,
        source: 'driver_cam',
        title: 'CRITICAL: Driver Microsleep!',
        message: `Driver eyes continuously closed for ${(drowsiness.continuousClosedDurationMs / 1000).toFixed(1)}s!`,
        durationMs: drowsiness.continuousClosedDurationMs,
      });
      return;
    }

    // High PERCLOS drowsiness
    if (drowsiness.severity !== 'normal' && this.canTriggerAlert('perclos', now)) {
      this.emitEvent({
        type: 'drowsiness',
        severity: drowsiness.severity,
        confidence: 0.90,
        source: 'driver_cam',
        title: 'Driver Drowsiness Alert',
        message: `High eye closure rate (PERCLOS: ${(drowsiness.perclos * 100).toFixed(0)}%).`,
        durationMs: 3000,
      });
      return;
    }

    // Head pose off-road gaze distraction (looking left, right, down, up)
    if (distraction.severity !== 'normal' && this.canTriggerAlert('distraction', now)) {
      this.emitEvent({
        type: 'distraction',
        severity: distraction.severity,
        confidence: 0.90,
        source: 'driver_cam',
        title: `Off-Road Gaze (${distraction.reason.replace('_', ' ').toUpperCase()})`,
        message: `Driver looking ${distraction.reason.replace('_', ' ')} for ${(distraction.offRoadDurationMs / 1000).toFixed(1)}s.`,
        durationMs: distraction.offRoadDurationMs,
      });
      return;
    }

    // Yawn fatigue warning
    if (yawn.isYawning && this.canTriggerAlert('yawn', now)) {
      this.emitEvent({
        type: 'yawn',
        severity: 'warn',
        confidence: 0.85,
        source: 'driver_cam',
        title: 'Driver Fatigue: Yawning',
        message: `Repeated yawning detected (${yawn.yawnCount} yawns logged).`,
        durationMs: yawn.yawnDurationMs,
      });
    }
  }

  private canTriggerAlert(key: string, now: number): boolean {
    const last = this.lastAlertTimestamp[key] || 0;
    if (now - last > this.ALERT_COOLDOWN_MS) {
      this.lastAlertTimestamp[key] = now;
      return true;
    }
    return false;
  }

  /**
   * Directly emit a safety event discovered by on-device computer vision models.
   */
  public emitVisionSafetyEvent(details: {
    type: SafetyEventType;
    severity: SafetyEventSeverity;
    confidence: number;
    source: 'driver_cam' | 'cabin_cam';
    title: string;
    message: string;
    durationMs: number;
  }): void {
    if (this.canTriggerAlert(details.type, Date.now())) {
      this.emitEvent(details);
    }
  }

  public setSnapshotProvider(provider: () => string | null): void {
    this.snapshotProvider = provider;
  }

  private emitEvent(details: {
    type: SafetyEventType;
    severity: SafetyEventSeverity;
    confidence: number;
    source: 'driver_cam' | 'cabin_cam';
    title: string;
    message: string;
    durationMs: number;
    thumbnail_ref?: string | null;
  }): void {
    const event: SafetyEvent = {
      event_id: `dms_ev_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
      trip_id: this.tripId,
      bus_id: this.busId,
      driver_id: this.driverId,
      school_id: this.schoolId,
      source: details.source,
      type: details.type,
      severity: details.severity,
      confidence: details.confidence,
      status: 'auto_flagged',
      detected_at: new Date().toISOString(),
      lat: this.currentLat,
      lng: this.currentLng,
      speed_kmph: this.currentSpeed,
      duration_ms: details.durationMs,
      clip_ref: null,
      thumbnail_ref: details.thumbnail_ref || (this.snapshotProvider ? this.snapshotProvider() : null),
      reviewed_by: null,
      reviewed_at: null,
      review_note: details.message,
    };

    this.activeAlert = {
      id: event.event_id,
      type: details.type,
      severity: details.severity,
      title: details.title,
      message: details.message,
      timestamp: event.detected_at,
    };

    // Auto-clear active alert banner from heads-up after 5 seconds
    setTimeout(() => {
      if (this.activeAlert?.id === event.event_id) {
        this.activeAlert = null;
      }
    }, 5000);

    // Notify listeners (UI overlay, Safety Score reducer, Incident Review Queue)
    this.listeners.forEach(listener => {
      try {
        listener(event);
      } catch (err) {
        console.error('Error notifying DMS listener:', err);
      }
    });

    // Broadcast across tabs/screens and persist for Admin Dashboard reflection
    dmsTelemetryBus.broadcastSafetyEvent(event).catch(() => {});
  }

  public dismissActiveAlert(): void {
    this.activeAlert = null;
  }

  public updateVisionMetrics(metrics: {
    isDriverPresent?: boolean;
    handsCount?: number;
    phoneInHand?: boolean;
    phoneDescription?: string;
    perclos?: number;
    isMicrosleeping?: boolean;
    isDistracted?: boolean;
    distractionReason?: GazeDistractionState['reason'];
    isYawning?: boolean;
    isUsingPhone?: boolean;
    phoneMode?: 'none' | 'calling' | 'texting';
    handsOnWheel?: boolean;
    seatbeltFastened?: boolean;
    headPose?: { yaw: number; pitch: number; roll: number; direction: string; isLookingAway?: boolean };
    attentionSummary?: string;
  }): void {
    const now = Date.now();
    if (metrics.isDriverPresent !== undefined) this.isDriverPresent = metrics.isDriverPresent;
    if (metrics.handsCount !== undefined) this.handsCount = metrics.handsCount;
    if (metrics.phoneDescription !== undefined) this.phoneDescription = metrics.phoneDescription;
    if (metrics.perclos !== undefined) this.latestVisionPerclos = metrics.perclos;
    if (metrics.isYawning !== undefined) this.latestVisionYawn = metrics.isYawning;
    if (metrics.phoneMode !== undefined) this.latestVisionPhoneMode = metrics.phoneMode;
    if (metrics.headPose !== undefined) this.latestHeadPose = metrics.headPose;
    if (metrics.attentionSummary !== undefined) this.latestAttentionSummary = metrics.attentionSummary;

    if (metrics.seatbeltFastened !== undefined) {
      if (!this.isSeatbeltManuallySet) {
        this.seatbeltFastened = metrics.seatbeltFastened;
      }
    }

    // =========================================================================
    // THE 4 CORE ANOMALY DETECTIONS:
    // (1) Phone in hand / texting and calling
    // (2) Both hands off wheel
    // (3) Looking left, right, down and up
    // (4) Microsleep
    // =========================================================================

    // (1) PHONE IN HAND / TEXTING AND CALLING
    if (metrics.phoneInHand !== undefined) this.phoneInHand = metrics.phoneInHand;
    if (metrics.isUsingPhone !== undefined) this.latestVisionPhone = metrics.isUsingPhone;
    const isPhoneEngaged = Boolean(this.phoneInHand || this.latestVisionPhone || (metrics.phoneMode && metrics.phoneMode !== 'none'));
    if (isPhoneEngaged) {
      if (this.phoneInHandStartTime === null) this.phoneInHandStartTime = now;
      const phoneDuration = now - this.phoneInHandStartTime;
      if (phoneDuration >= 1200 && this.canTriggerAlert('phone_use', now)) {
        const modeDesc = this.latestVisionPhoneMode === 'calling'
          ? 'Calling (Near Ear)'
          : this.latestVisionPhoneMode === 'texting'
          ? 'Texting / Lap'
          : this.phoneDescription || 'Phone In Hand';
        this.emitEvent({
          type: 'phone_use',
          severity: 'critical',
          confidence: 0.94,
          source: 'driver_cam',
          title: `Mobile Phone In Use (${modeDesc})`,
          message: `Driver operating mobile phone (${modeDesc}) while driving.`,
          durationMs: phoneDuration,
        });
      }
    } else {
      this.phoneInHandStartTime = null;
    }

    // (2) BOTH HANDS OFF WHEEL
    if (metrics.handsOnWheel !== undefined) {
      this.handsOnWheel = metrics.handsOnWheel;
      if (!this.handsOnWheel) {
        if (this.handsOffStartTime === null) this.handsOffStartTime = now;
        const duration = now - this.handsOffStartTime;
        if (duration >= 2500 && this.canTriggerAlert('hands_off', now)) {
          this.emitEvent({
            type: 'hands_off',
            severity: 'critical',
            confidence: 0.92,
            source: 'driver_cam',
            title: 'Both Hands Off Steering Wheel',
            message: 'Driver has both hands removed from steering wheel for >2.5s.',
            durationMs: duration,
          });
        }
      } else {
        this.handsOffStartTime = null;
      }
    }

    // (3) LOOKING LEFT, RIGHT, DOWN AND UP (OFF-ROAD GAZE DISTRACTION)
    if (metrics.isDistracted !== undefined) this.latestVisionDistracted = metrics.isDistracted;
    if (metrics.distractionReason !== undefined) this.latestVisionDistractionReason = metrics.distractionReason;
    if (this.latestVisionDistracted) {
      if (this.distractionStartTime === null) this.distractionStartTime = now;
      const distDuration = now - this.distractionStartTime;
      if (distDuration >= 2000 && this.canTriggerAlert('distraction', now)) {
        const dir = (this.latestVisionDistractionReason || 'away').replace('_', ' ').toUpperCase();
        this.emitEvent({
          type: 'distraction',
          severity: distDuration >= 3500 ? 'critical' : 'warn',
          confidence: 0.90,
          source: 'driver_cam',
          title: `Off-Road Gaze (${dir})`,
          message: `Driver looking ${this.latestVisionDistractionReason?.replace('_', ' ') || 'away'} for ${(distDuration / 1000).toFixed(1)}s.`,
          durationMs: distDuration,
        });
      }
    } else {
      this.distractionStartTime = null;
    }

    // (4) MICROSLEEP (CLOSED EYES / HIGH PERCLOS)
    if (metrics.isMicrosleeping !== undefined) this.latestVisionMicrosleep = metrics.isMicrosleeping;
    if (this.latestVisionMicrosleep) {
      if (this.microsleepStartTime === null) this.microsleepStartTime = now;
      const sleepDuration = now - this.microsleepStartTime;
      if (sleepDuration >= 1400 && this.canTriggerAlert('drowsiness_crit', now)) {
        this.emitEvent({
          type: 'drowsiness',
          severity: 'critical',
          confidence: 0.96,
          source: 'driver_cam',
          title: 'CRITICAL: Driver Microsleep!',
          message: `Driver eyes continuously closed for ${(sleepDuration / 1000).toFixed(1)}s!`,
          durationMs: sleepDuration,
        });
      }
    } else {
      this.microsleepStartTime = null;
    }
    if (metrics.headPose !== undefined) this.latestHeadPose = metrics.headPose;
    if (metrics.attentionSummary !== undefined) this.latestAttentionSummary = metrics.attentionSummary;
  }

  public toggleSeatbelt(): boolean {
    this.seatbeltFastened = !this.seatbeltFastened;
    this.isSeatbeltManuallySet = true;
    return this.seatbeltFastened;
  }

  public setSeatbelt(fastened: boolean): void {
    this.seatbeltFastened = fastened;
    this.isSeatbeltManuallySet = true;
  }

  public clearSeatbeltManualOverride(): void {
    this.isSeatbeltManuallySet = false;
  }

  public isSeatbeltFastened(): boolean {
    return this.seatbeltFastened;
  }

  public getStatus(
    drowsiness?: DrowsinessState,
    distraction?: GazeDistractionState,
    yawn?: YawnState
  ): DMSStatus {
    const dState: DrowsinessState = drowsiness || {
      currentEAR: this.latestVisionMicrosleep ? 0.05 : 0.32,
      isEyesClosed: this.latestVisionMicrosleep,
      continuousClosedDurationMs: this.latestVisionMicrosleep ? 1800 : 0,
      perclos: this.latestVisionPerclos,
      isMicrosleeping: this.latestVisionMicrosleep,
      isDrowsy: this.latestVisionPerclos > 0.35,
      severity: this.latestVisionMicrosleep ? 'critical' : this.latestVisionPerclos > 0.35 ? 'warn' : 'normal',
    };

    const distState: GazeDistractionState = distraction || {
      isDistracted: this.latestVisionDistracted,
      offRoadDurationMs: this.latestVisionDistracted ? 2500 : 0,
      reason: this.latestVisionDistractionReason,
      severity: this.latestVisionDistracted ? 'warn' : 'normal',
    };

    const yState: YawnState = yawn || {
      isYawning: this.latestVisionYawn,
      yawnDurationMs: this.latestVisionYawn ? 2200 : 0,
      yawnCount: this.latestVisionYawn ? 1 : 0,
      severity: this.latestVisionYawn ? 'warn' : 'normal',
    };

    return {
      isDriverPresent: this.isDriverPresent,
      handsCount: this.handsCount,
      phoneInHand: this.phoneInHand,
      phoneDescription: this.phoneDescription,
      drowsiness: dState,
      distraction: distState,
      yawn: yState,
      phone: {
        isUsingPhone: this.latestVisionPhone,
        mode: this.latestVisionPhoneMode,
        confidence: this.latestVisionPhone ? 0.94 : 0,
        severity: this.latestVisionPhone ? 'critical' : 'normal',
      },
      handsOnWheel: this.handsOnWheel,
      seatbeltFastened: this.seatbeltFastened,
      activeAlert: this.activeAlert,
      headPose: this.latestHeadPose,
      attentionSummary: this.latestAttentionSummary,
    };
  }

  public reset(): void {
    this.perclosTracker.reset();
    this.distractionTracker.reset();
    this.activeAlert = null;
    this.lastAlertTimestamp = {};
    this.handsOffStartTime = null;
    this.seatbeltOffStartTime = null;
    this.driverAbsentStartTime = null;
    this.phoneInHandStartTime = null;
    this.distractionStartTime = null;
    this.microsleepStartTime = null;
    this.isDriverPresent = false;
    this.handsCount = 2;
    this.phoneInHand = false;
    this.phoneDescription = 'Clear';
    this.seatbeltFastened = false;
    this.isSeatbeltManuallySet = false;
    this.latestVisionPerclos = 0.05;
    this.latestVisionMicrosleep = false;
    this.latestVisionDistracted = false;
    this.latestVisionDistractionReason = 'normal';
    this.latestVisionYawn = false;
    this.latestVisionPhone = false;
    this.latestVisionPhoneMode = 'none';
    this.latestHeadPose = { yaw: 0, pitch: 0, roll: 0, direction: 'SEARCHING...', isLookingAway: false };
    this.latestAttentionSummary = 'INITIALIZING REAL-TIME DMS...';
  }
}

// Singleton DMS Engine Instance
export const dmsEngine = new DMSEngine();
